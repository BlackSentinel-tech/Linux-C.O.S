#!/bin/sh
# Linux-C.O.S -- behaviour tests for the shipped CLI tools (cos-stacks,
# blackarch-shell, cos-help, cos-pause) against a fake `docker`, so they run
# anywhere without a daemon: tests/cli/run.sh
set -u
cd "$(dirname "$0")/../.." || exit 1

INC=$PWD/build/config/includes.chroot
BIN=$INC/usr/local/bin
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT INT TERM

mkdir -p "$WORK/bin" "$WORK/home"
cat > "$WORK/bin/docker" <<'EOF'
#!/bin/sh
echo "docker $*" >> "$MOCK_LOG"
case "$1" in
  info) [ -n "${MOCK_DOWN:-}" ] && exit 1; exit 0 ;;
  compose)
    [ "$2" = version ] && exit 0
    # like real compose: ${VAR:?} in the compose file fails without the env file
    file=''; envf=''; prev=''
    for a in "$@"; do
      [ "$prev" = -f ] && file=$a
      [ "$prev" = --env-file ] && envf=$a
      prev=$a
    done
    if [ -n "$file" ] && grep -q ':?' "$file" && { [ -z "$envf" ] || [ ! -f "$envf" ]; }; then
      echo "required variable is missing a value" >&2; exit 1
    fi
    exit 0 ;;
  image) [ -n "${MOCK_IMAGE:-}" ] && exit 0; exit 1 ;;
  ps)
    case " $* " in
      *"label=com.docker.compose.project"*) [ -n "${MOCK_RUNNING:-}" ] && echo abc123 ;;
      *) [ -n "${MOCK_CONTAINER:-}" ] && echo blackarch-tools ;;
    esac
    exit 0 ;;
esac
exit 0
EOF
chmod +x "$WORK/bin/docker"

export PATH="$WORK/bin:$PATH" HOME="$WORK/home" MOCK_LOG="$WORK/docker.log" \
       COS_STACKS_DIR="$INC/opt/linux-cos/blueteam-stacks" NO_COLOR=1
unset XDG_CONFIG_HOME XDG_DATA_HOME
: > "$MOCK_LOG"

pass=0; failed=0
check() { # check <description> <expected-rc> <grep-pattern|-> <cmd...>
  desc=$1; want=$2; pat=$3; shift 3
  out=$("$@" 2>&1 </dev/null); rc=$?
  if [ "$rc" -ne "$want" ]; then
    printf 'FAIL %s (rc=%s, want %s)\n%s\n' "$desc" "$rc" "$want" "$out"; failed=$((failed + 1)); return
  fi
  if [ "$pat" != - ] && ! printf '%s' "$out" | grep -qE -- "$pat"; then
    printf 'FAIL %s (output lacks /%s/)\n%s\n' "$desc" "$pat" "$out"; failed=$((failed + 1)); return
  fi
  printf 'ok   %s\n' "$desc"; pass=$((pass + 1))
}

CS="$BIN/cos-stacks"
check "cos-stacks: no args without a TTY prints usage" 1 "usage:" sh "$CS"
check "cos-stacks help" 0 "cos-stacks creds" sh "$CS" help
check "cos-stacks list shows every stack" 0 "thehive-cortex +stopped" sh "$CS" list
check "cos-stacks list: wazuh listed" 0 "^wazuh" sh "$CS" list
check "cos-stacks info misp" 0 "https://localhost:8443" sh "$CS" info misp
check "cos-stacks up without a name lists stacks" 1 "missing stack name" sh "$CS" up
check "cos-stacks rejects path traversal" 1 "unknown stack" sh "$CS" up ../../etc
check "cos-stacks rejects unknown stack" 1 "unknown stack \"mispp\"" sh "$CS" up mispp
check "cos-stacks unknown command" 1 "unknown command" sh "$CS" frobnicate
check "cos-stacks creds before up explains how" 1 "generated by: cos-stacks up misp" sh "$CS" creds misp
check "cos-stacks down before up explains how" 1 "never started here" sh "$CS" down misp
check "cos-stacks logs before up explains how" 1 "never started here" sh "$CS" logs misp
check "cos-stacks up misp" 0 "Web UI: https://localhost:8443" sh "$CS" up misp
check "cos-stacks up passes the env file + project" 0 "compose -p cos-misp --env-file .*misp.env" cat "$MOCK_LOG"
check "thehive up does not claim to generate passwords" 1 - sh -c "sh '$CS' up thehive-cortex | grep -q 'generating'"
check "thehive creds says to change the default" 0 "change it on first login" sh "$CS" creds thehive-cortex
check "wazuh creds warns about upstream defaults" 0 "SecretPassword" sh "$CS" creds wazuh
check "cos-stacks creds after up" 0 "^MISP_ADMIN_PASSPHRASE=[A-Za-z0-9]{24}$" sh "$CS" creds misp

envf="$HOME/.config/linux-cos/stacks/misp.env"
perm=$(stat -c %a "$envf" 2>/dev/null || stat -f %Lp "$envf")
check "secrets file is private (600)" 0 "^600$" echo "$perm"
first=$(cat "$envf")
sh "$CS" up misp >/dev/null 2>&1
check "secrets are stable across runs" 0 - test "$first" = "$(cat "$envf")"
check "status shows running" 0 "misp +running" env MOCK_RUNNING=1 sh "$CS" list
check "status of a started stack works" 0 - sh "$CS" status misp
check "down after up works" 0 "misp stopped" sh "$CS" down misp
check "docker down -> clear error" 1 "Docker daemon is not running" env MOCK_DOWN=1 sh "$CS" up misp
check "menu: invalid then quit" 0 "Not a valid choice" sh -c "printf 'x\n99\nq\n' | sh '$CS' menu"
check "menu: 0 is rejected without errors" 0 "^[^b]*Not a valid choice" sh -c "printf '0\nq\n' | sh '$CS' menu 2>&1"
check "menu: empty input refreshes instead of quitting" 0 "Pick a stack.*Pick a stack" sh -c "printf '\nq\n' | sh '$CS' menu | tr '\n' ' '"
check "menu: unknown action key is explained" 0 "Unknown key" sh -c "printf '1\nx\nb\nq\n' | sh '$CS' menu"
check "menu: EOF exits cleanly" 0 - sh -c "printf '' | sh '$CS' menu"
check "menu lines fit 80 columns" 0 - sh -c "printf 'q\n' | COLUMNS=80 sh '$CS' menu | awk 'length > 80 { exit 1 }'"
check "list fits 80 columns" 0 - sh -c "COLUMNS=80 sh '$CS' list | awk 'length > 80 { exit 1 }'"
check "menu: pick a stack shows its info" 0 "what   : MISP" sh -c "printf '1\nb\nq\n' | sh '$CS' menu"

BA="$BIN/blackarch-shell"
check "blackarch-shell --help" 0 "blackarch-shell --update" sh "$BA" --help
check "blackarch-shell unknown option" 1 "unknown option" sh "$BA" --bogus
check "blackarch-shell without image explains" 1 "blackarch-shell --update" sh "$BA"
check "blackarch-shell --status (missing)" 0 "image: +missing" sh "$BA" --status
: > "$MOCK_LOG"
check "blackarch-shell runs a one-off command" 0 - env MOCK_IMAGE=1 sh "$BA" nmap -h
check "one-off command uses docker run, no TTY" 0 "docker run -i --rm --name blackarch-tools .* linux-cos/blackarch:latest nmap -h" cat "$MOCK_LOG"
: > "$MOCK_LOG"
check "blackarch-shell joins a running container" 0 - env MOCK_IMAGE=1 MOCK_CONTAINER=1 sh "$BA" id
check "join uses docker exec" 0 "docker exec -i -w .* blackarch-tools id" cat "$MOCK_LOG"

check "cos-help English" 0 "Offense" env LANG=en_US.UTF-8 sh "$BIN/cos-help"
check "cos-help Spanish" 0 "Ofensiva" env LANG=es_ES.UTF-8 sh "$BIN/cos-help"
check "cos-help --es topic" 0 "Defensiva" env LANG=C sh "$BIN/cos-help" --es defense
check "cos-help bad topic" 1 "Unknown topic: \"nope\"" env LANG=C sh "$BIN/cos-help" nope
check "cos-help output fits 80 columns" 0 - sh -c "for l in C es_ES.UTF-8; do LANG=\$l sh '$BIN/cos-help'; done | awk 'length > 80 { exit 1 }'"
check "blackarch-shell -- ends options" 0 - env MOCK_IMAGE=1 sh "$BA" -- ls -la
check "cos-pause keeps the exit status" 3 "Press Enter" sh -c "printf '\n' | sh '$BIN/cos-pause' sh -c 'exit 3'"

echo
echo "cli tests: $pass passed, $failed failed"
[ "$failed" -eq 0 ]
