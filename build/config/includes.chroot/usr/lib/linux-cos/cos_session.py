# --- apply / start -----------------------------------------------------------------------------
def _monitors() -> list[str]:
    """Names xfdesktop uses for the outputs: monitor0, monitor<output>, ..."""
    names = ["monitor0", "monitorVirtual-1"]
    try:
        out = subprocess.run(["xrandr", "--listactivemonitors"], capture_output=True, text=True, timeout=10).stdout
        for line in out.splitlines()[1:]:
            if line.split():
                names.append("monitor" + line.split()[-1])
    except (OSError, subprocess.SubprocessError):
        pass
    return list(dict.fromkeys(names))


def _wallpaper(mode: str, animated: bool) -> None:
    static = f"{BG}/{mode}.jpg"
    for mon in _monitors():
        for ws in range(4):
            base = f"/backdrop/screen0/{mon}/workspace{ws}"
            _xfset("xfce4-desktop", f"{base}/last-image", "string", static)
            _xfset("xfce4-desktop", f"{base}/image-style", "int", "5")
    if animated and shutil.which("python3") and os.path.exists(f"{LIB}/cos_wallpaperd.py"):
        _run("xfdesktop", "--quit")
        _run("pkill", "-u", str(os.getuid()), "-f", "cos_wallpaperd.py")
        _spawn("python3", f"{LIB}/cos_wallpaperd.py")
    else:
        _run("pkill", "-u", str(os.getuid()), "-f", "cos_wallpaperd.py")
        if _run("pgrep", "-u", str(os.getuid()), "-x", "xfdesktop") != 0:
            _spawn("xfdesktop")
        else:
            _run("xfdesktop", "--reload")


def apply() -> None:
    if not (os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY")):
        # never pkill/spawn anything without a desktop (ssh, tests, a dev machine)
        raise RuntimeError("no desktop session")
    mode, fx = core.get_mode(), core.effective_fx()
    p = core.palette(mode)
    theme = "COS-" + mode.capitalize()

    # toolkit look
    _xfset("xsettings", "/Net/ThemeName", "string", theme)
    _xfset("xsettings", "/Net/IconThemeName", "string", "Papirus-Dark")
    _xfset("xfwm4", "/general/theme", "string", theme)
    _xfset("xfwm4", "/general/use_compositing", "bool", "true" if fx == "off" else "false")

    # terminal / prompt / launcher palette
    _write(os.path.expanduser("~/.config/xfce4/terminal/terminalrc"), terminalrc(p))
    _write(os.path.join(CFG, "starship.toml"), starship_conf(p))
    apply_rofi(p)
    apply_conky(p, mode)

    # compositor -- if the GLX profile cannot start (no GL, odd driver), fall back to xrender
    _kill("picom")
    if fx in ("high", "low") and shutil.which("picom"):
        conf = os.path.join(CFG, "picom.conf")
        _write(conf, picom_conf(fx))
        _spawn("picom", "--config", conf)
        if fx == "high":
            time.sleep(1.5)
            if _run("pgrep", "-u", str(os.getuid()), "-x", "picom") != 0:
                _write(conf, picom_conf("low"))
                _spawn("picom", "--config", conf)

    _wallpaper(mode, animated=(fx == "high"))

    # HUD
    _kill("conky")
    if fx in ("high", "low") and shutil.which("conky"):
        time.sleep(1.5)  # after the wallpaper, so the HUD is stacked above it
        _spawn("conky", "-c", os.path.join(CFG, "conky", "conky.conf"))


def prompt() -> None:
    """Write only the shell prompt config (cheap; used by new shells before the desktop session ran)."""
    _write(os.path.join(CFG, "starship.toml"), starship_conf(core.palette(core.get_mode())))


def start() -> None:
    """Login: give the desktop a moment to come up, then apply the saved choice."""
    for _ in range(40):
        if _run("xfconf-query", "-c", "xsettings", "-l") == 0:
            break
        time.sleep(0.5)
    apply()
