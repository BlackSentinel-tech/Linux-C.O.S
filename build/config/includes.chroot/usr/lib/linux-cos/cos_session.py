    cfg = os.path.join(d, "config.rasi")
    if not os.path.exists(cfg):
        _write(cfg, '@theme "cos"\nconfiguration {\n  modes: "drun,run,window";\n  show-icons: true;\n  display-drun: "COS";\n  drun-display-format: "{name}";\n}\n')


