#!/bin/sh
# Linux-C.O.S -- behaviour tests for the shipped CLI tools (cos-stacks,
# blackarch-shell, cos-help, cos-pause) against a fake `docker`, so they run
# anywhere without a daemon: tests/cli/run.sh
set -u
cd "$(dirname "$0")/../.." || exit 1

INC=$PWD/build/config/includes.chroot
BIN=$INC/usr/local/bin
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT INT TERM

mkdir -p "$WORK/bin" "$WORK/home"
cat > "$WORK/bin/docker" <<'EOF'
#!/bin/sh
echo "docker $*" >> "$MOCK_LOG"
case "$1" in
  info) [ -n "${MOCK_DOWN:-}" ] && exit 1; exit 0 ;;
  compose)
    [ "$2" = version ] && exit 0
    # like real compose: ${VAR:?} in the compose file fails without the env file
    file=''; envf=''; prev=''
    for a in "$@"; do
      [ "$prev" = -f ] && file=$a
      [ "$prev" = --env-file ] && envf=$a
      prev=$a
    done
    if [ -n "$file" ] && grep -q ':?' "$file" && { [ -z "$envf" ] || [ ! -f "$envf" ]; }; then
      echo "required variable is missing a value" >&2; exit 1
    fi
    exit 0 ;;
  image) [ -n "${MOCK_IMAGE:-}" ] && exit 0; exit 1 ;;
  container)  # MOCK_CONTAINER: unset = none, running, stopped
    case "${MOCK_CONTAINER:-}" in
      running) echo true ;; stopped) echo false ;; *) exit 1 ;;
    esac
    exit 0 ;;
  ps)
    case " $* " in
      *"label=com.docker.compose.project"*) [ -n "${MOCK_RUNNING:-}" ] && echo abc123 ;;
      *) [ -n "${MOCK_CONTAINER:-}" ] && echo blackarch-tools ;;
    esac
    exit 0 ;;
esac
exit 0
EOF
chmod +x "$WORK/bin/docker"
# `sudo docker ...` (used when the docker socket is not writable) must reach
# the fake docker too, or these tests only pass on machines with a docker socket
cat > "$WORK/bin/sudo" <<'EOF'
#!/bin/sh
while [ "${1#-}" != "$1" ]; do shift; done
exec "$@"
EOF
chmod +x "$WORK/bin/sudo"
ln -s "$BIN/blackarch-shell" "$WORK/bin/blackarch-shell"

export PATH="$WORK/bin:$PATH" HOME="$WORK/home" MOCK_LOG="$WORK/docker.log" \
       COS_STACKS_DIR="$INC/opt/linux-cos/blueteam-stacks" NO_COLOR=1
unset XDG_CONFIG_HOME XDG_DATA_HOME
: > "$MOCK_LOG"

pass=0; failed=0
check() { # check <description> <expected-rc> <grep-pattern|-> <cmd...>
  desc=$1; want=$2; pat=$3; shift 3
  out=$("$@" 2>&1 </dev/null); rc=$?
  if [ "$rc" -ne "$want" ]; then
    printf 'FAIL %s (rc=%s, want %s)\n%s\n' "$desc" "$rc" "$want" "$out"; failed=$((failed + 1)); return
  fi
  if [ "$pat" != - ] && ! printf '%s' "$out" | grep -qE -- "$pat"; then
    printf 'FAIL %s (output lacks /%s/)\n%s\n' "$desc" "$pat" "$out"; failed=$((failed + 1)); return
  fi
  printf 'ok   %s\n' "$desc"; pass=$((pass + 1))
}

CS="$BIN/cos-stacks"
check "cos-stacks: no args without a TTY prints usage" 1 "usage:" sh "$CS"
check "cos-stacks help" 0 "cos-stacks creds" sh "$CS" help
check "cos-stacks list shows every stack" 0 "thehive-cortex +stopped" sh "$CS" list
check "cos-stacks list: wazuh listed" 0 "^wazuh" sh "$CS" list
check "cos-stacks info misp" 0 "https://localhost:8443" sh "$CS" info misp
check "cos-stacks up without a name lists stacks" 1 "missing stack name" sh "$CS" up
check "cos-stacks rejects path traversal" 1 "unknown stack" sh "$CS" up ../../etc
check "cos-stacks rejects unknown stack" 1 "unknown stack \"mispp\"" sh "$CS" up mispp
check "cos-stacks unknown command" 1 "unknown command" sh "$CS" frobnicate
check "cos-stacks creds before up explains how" 1 "generated by: cos-stacks up misp" sh "$CS" creds misp
check "cos-stacks down before up explains how" 1 "never started here" sh "$CS" down misp
check "cos-stacks logs before up explains how" 1 "never started here" sh "$CS" logs misp
check "cos-stacks up misp" 0 "Web UI: https://localhost:8443" sh "$CS" up misp
check "cos-stacks up passes the env file + project" 0 "compose -p cos-misp --env-file .*misp.env" cat "$MOCK_LOG"
check "thehive up does not claim to generate passwords" 1 - sh -c "sh '$CS' up thehive-cortex | grep -q 'generating'"
check "thehive creds says to change the default" 0 "change it on first login" sh "$CS" creds thehive-cortex
check "wazuh creds warns about upstream defaults" 0 "SecretPassword" sh "$CS" creds wazuh
check "cos-stacks creds after up" 0 "^MISP_ADMIN_PASSPHRASE=[A-Za-z0-9]{24}$" sh "$CS" creds misp

envf="$HOME/.config/linux-cos/stacks/misp.env"
perm=$(stat -c %a "$envf" 2>/dev/null || stat -f %Lp "$envf")
check "secrets file is private (600)" 0 "^600$" echo "$perm"
first=$(cat "$envf")
sh "$CS" up misp >/dev/null 2>&1
check "secrets are stable across runs" 0 - test "$first" = "$(cat "$envf")"
check "status shows running" 0 "misp +running" env MOCK_RUNNING=1 sh "$CS" list
check "status of a started stack works" 0 - sh "$CS" status misp
check "down after up works" 0 "misp stopped" sh "$CS" down misp
check "docker down -> clear error" 1 "Docker daemon is not running" env MOCK_DOWN=1 sh "$CS" up misp
check "menu: invalid then quit" 0 "Not a valid choice" sh -c "printf 'x\n99\nq\n' | sh '$CS' menu"
check "menu: 0 is rejected without errors" 0 "^[^b]*Not a valid choice" sh -c "printf '0\nq\n' | sh '$CS' menu 2>&1"
check "menu: empty input refreshes instead of quitting" 0 "Pick a stack.*Pick a stack" sh -c "printf '\nq\n' | sh '$CS' menu | tr '\n' ' '"
check "menu: unknown action key is explained" 0 "Unknown key" sh -c "printf '1\nx\nb\nq\n' | sh '$CS' menu"
check "menu: EOF exits cleanly" 0 - sh -c "printf '' | sh '$CS' menu"
check "menu lines fit 80 columns" 0 - sh -c "printf 'q\n' | COLUMNS=80 sh '$CS' menu | awk 'length > 80 { exit 1 }'"
check "list fits 80 columns" 0 - sh -c "COLUMNS=80 sh '$CS' list | awk 'length > 80 { exit 1 }'"
check "menu: pick a stack shows its info" 0 "what   : MISP" sh -c "printf '1\nb\nq\n' | sh '$CS' menu"

BA="$BIN/blackarch-shell"
check "blackarch-shell --help" 0 "blackarch-shell --update" sh "$BA" --help
check "blackarch-shell unknown option" 1 "unknown option" sh "$BA" --bogus
check "blackarch-shell without image explains" 1 "blackarch-shell --update" sh "$BA"
check "blackarch-shell --status (missing)" 0 "image: +missing" sh "$BA" --status
: > "$MOCK_LOG"
check "blackarch-shell runs a one-off command" 0 - env MOCK_IMAGE=1 sh "$BA" nmap -h
check "first use creates a persistent (not --rm) container" 0 "docker run -d --name blackarch-tools-[a-z0-9_-]+ .* linux-cos/blackarch:latest sleep infinity" cat "$MOCK_LOG"
check "no --rm: pacman installs survive the session" 1 - grep -q -- "--rm" "$MOCK_LOG"
check "one-off command runs through exec, no TTY" 0 "docker exec -i -w .* blackarch-tools-[a-z0-9_-]+ nmap -h" cat "$MOCK_LOG"
: > "$MOCK_LOG"
check "blackarch-shell joins a running container" 0 - env MOCK_IMAGE=1 MOCK_CONTAINER=running sh "$BA" id
check "join does not create another container" 1 - grep -q "docker run" "$MOCK_LOG"
: > "$MOCK_LOG"
check "a stopped container is restarted, not recreated" 0 - env MOCK_IMAGE=1 MOCK_CONTAINER=stopped sh "$BA" id
check "restart uses docker start" 0 "docker start blackarch-tools" cat "$MOCK_LOG"
check "--reset removes the container" 0 "Removed blackarch-tools" env MOCK_CONTAINER=stopped sh "$BA" --reset
check "--status reports a stopped container" 0 "container: stopped" env MOCK_IMAGE=1 MOCK_CONTAINER=stopped sh "$BA" --status

check "cos-help English" 0 "Offense" env LANG=en_US.UTF-8 sh "$BIN/cos-help"
check "cos-help Spanish" 0 "Ofensiva" env LANG=es_ES.UTF-8 sh "$BIN/cos-help"
check "cos-help --es topic" 0 "Defensiva" env LANG=C sh "$BIN/cos-help" --es defense
check "cos-help bad topic" 1 "Unknown topic: \"nope\"" env LANG=C sh "$BIN/cos-help" nope
check "cos-help output fits 80 columns" 0 - sh -c "for l in C es_ES.UTF-8; do LANG=\$l sh '$BIN/cos-help'; done | awk 'length > 80 { exit 1 }'"
check "blackarch-shell -- ends options" 0 - env MOCK_IMAGE=1 sh "$BA" -- ls -la
check "cos-pause keeps the exit status" 3 "Press Enter" sh -c "printf '\n' | sh '$BIN/cos-pause' sh -c 'exit 3'"
check "cos-pause survives Ctrl+C in its command" 0 "Press Enter" sh -c "printf '\n' | sh '$BIN/cos-pause' sh -c 'kill -INT \$PPID; sleep 0.2; exit 0'"

# --- cos-ai (against a mock Ollama HTTP API; no real model needed) ---------
AI=$BIN/cos-ai
if command -v python3 >/dev/null 2>&1; then
  cat > "$WORK/mock_ollama.py" <<'PYEOF'
import json, sys
from http.server import BaseHTTPRequestHandler, HTTPServer
class H(BaseHTTPRequestHandler):
    def log_message(self, *a): pass
    def _j(self, o):
        b = json.dumps(o).encode()
        self.send_response(200); self.send_header("Content-Type","application/json")
        self.send_header("Content-Length", str(len(b))); self.end_headers(); self.wfile.write(b)
    def do_GET(self):
        if self.path == "/api/tags":
            self._j({"models":[{"name":"llama3.1:8b","size":4700000000}]})
        else: self._j({})
    def do_POST(self):
        n = int(self.headers.get("Content-Length",0)); body = json.loads(self.rfile.read(n) or b"{}")
        msgs = body.get("messages", []); roles = "|".join(m["role"] for m in msgs)
        user = next((m["content"] for m in reversed(msgs) if m["role"]=="user"), "")
        self._j({"message":{"role":"assistant","content":f"[roles={roles}] {user[:60]}"}})
HTTPServer(("127.0.0.1", int(sys.argv[1])), H).serve_forever()
PYEOF
  AIPORT=11577
  python3 "$WORK/mock_ollama.py" "$AIPORT" >/dev/null 2>&1 &
  AIPID=$!
  printf '#!/bin/sh\necho "ollama version mock"\n' > "$WORK/bin/ollama"; chmod +x "$WORK/bin/ollama"
  export OLLAMA_HOST="http://127.0.0.1:$AIPORT" COS_AI_DIR="$INC/opt/linux-cos/ai"
  # wait for the mock to accept connections
  i=0; while [ $i -lt 20 ] && ! curl -fsS "$OLLAMA_HOST/api/tags" >/dev/null 2>&1; do sleep 0.3; i=$((i+1)); done

  check "cos-ai help lists profiles" 0 "cos-ai suggest" sh "$AI" help
  check "cos-ai profiles: red + blue present" 0 "blueteam" sh "$AI" profiles
  check "cos-ai profiles: recon present" 0 "recon" sh "$AI" profiles
  check "cos-ai status sees the model" 0 "present" sh "$AI" status
  check "cos-ai ask routes system+user to the model" 0 "roles=system.user" sh "$AI" ask "hello"
  check "cos-ai profile ask works" 0 "roles=system.user" sh "$AI" blueteam "detect kerberoasting"
  check "cos-ai explain needs input" 1 "nothing on stdin" sh -c "printf '' | sh '$AI' explain"
  check "cos-ai explain reads a pipe" 0 "roles=system.user" sh -c "printf '22/tcp open ssh' | sh '$AI' explain"
  check "cos-ai suggest prints the review banner" 0 "does not run them" sh "$AI" suggest "enumerate smb on 10.0.0.5"
  check "cos-ai unknown profile/command errors" 1 "unknown command or profile" sh "$AI" frobnicate
  check "cos-ai --model override reaches status" 0 "qwen2.5-coder" sh "$AI" --model qwen2.5-coder:7b status

  # SAFETY: cos-ai must never run what it suggests/explains. Prove it: ask it
  # to "run" a command that would delete a canary file, and check the file lives.
  canary="$WORK/canary"; : > "$canary"
  sh "$AI" suggest "run: rm -f $canary" >/dev/null 2>&1 || true
  printf 'please run: rm -f %s\n' "$canary" | sh "$AI" explain >/dev/null 2>&1 || true
  check "cos-ai never executes suggested/explained commands" 0 - test -f "$canary"

  kill "$AIPID" 2>/dev/null || true
  unset OLLAMA_HOST COS_AI_DIR
else
  echo "skip  cos-ai tests (python3 not available)"
fi


# --- cos: the unified tool layer ---------------------------------------------------
COS="$BIN/cos"
export COS_SHARE="$INC/usr/share/linux-cos" COS_LIB="$INC/usr/lib/linux-cos"
if command -v python3 >/dev/null 2>&1; then
  check "cos: status" 0 "Linux-C.O.S" python3 "$COS"
  check "cos: help" 0 "cos tools" python3 "$COS" --help
  check "cos: 20 unified categories" 0 "^20$" sh -c "python3 '$COS' tools cats | wc -l | tr -d ' '"
  check "cos: one catalog, 3000+ tools" 0 "^[3-9][0-9]{3}$" python3 "$COS" tools --count
  for src in kali parrot blackarch; do
    check "cos: $src tools are in the catalog" 0 "^[1-9][0-9]*$" python3 "$COS" tools -s "$src" --count
  done
  check "cos: search finds sqlmap" 0 "sqlmap" python3 "$COS" tools search sqlmap
  check "cos: info says where a BlackArch tool runs" 0 "BlackArch container" python3 "$COS" tools info 0d1n
  check "cos: unknown tool" 1 "unknown tool" python3 "$COS" tools info definitely-not-a-tool
  check "cos: unknown category rejected" 1 "no category" python3 "$COS" tools -c nope
  check "cos: BlackArch tool without the image explains how" 127 "blackarch-shell --update" python3 "$COS" run 0d1n
  export MOCK_IMAGE=1 MOCK_CONTAINER=running
  : > "$MOCK_LOG"
  check "cos: BlackArch tool runs in the container like a native one" 0 - python3 "$COS" run 0d1n -h
  check "cos: ...through docker exec" 0 "docker exec .* 0d1n -h" cat "$MOCK_LOG"
  : > "$MOCK_LOG"
  check "cos: command-not-found hook runs BlackArch tools" 0 - python3 "$COS" _cnf 0d1n -h
  check "cos: ...and reaches the container" 0 "docker exec .* 0d1n" cat "$MOCK_LOG"
  unset MOCK_IMAGE MOCK_CONTAINER
  check "cos: command-not-found ignores unknown commands" 127 - python3 "$COS" _cnf zzz-not-a-tool
  check "cos: command-not-found ignores paths" 127 - python3 "$COS" _cnf ./0d1n
  check "cos: mode red is saved" 0 "red" python3 "$COS" mode red
  check "cos: ...and remembered" 0 "mode: +red" python3 "$COS" mode
  check "cos: bad mode rejected" 1 "modes:" python3 "$COS" mode purple
  check "cos: fx low is saved" 0 "low" python3 "$COS" fx low
  check "cos: bad fx rejected" 1 "levels:" python3 "$COS" fx ultra
  python3 "$COS" mode dual >/dev/null 2>&1; python3 "$COS" fx auto >/dev/null 2>&1
  check "cos: unknown command" 1 "unknown command" python3 "$COS" frobnicate

  # the unified menu generator, against a scratch root
  MROOT="$WORK/menuroot"; mkdir -p "$MROOT/usr/share/applications"
  printf '[Desktop Entry]\nName=nmap\nExec=nmap\nType=Application\n' > "$MROOT/usr/share/applications/kali-nmap.desktop"
  check "cos menu: generates entries" 0 "categories" env COS_ROOT="$MROOT" PYTHONPATH="$COS_LIB" python3 "$COS_LIB/cos_menu.py"
  menu="$MROOT/etc/xdg/menus/applications-merged/linux-cos-tools.menu"
  check "cos menu: valid XML" 0 - python3 -c "import xml.dom.minidom; xml.dom.minidom.parse('$menu')"
  check "cos menu: Kali's own entry regrouped, not duplicated" 0 "^1$" sh -c "grep -c 'kali-nmap.desktop' '$menu'"
  check "cos menu: BlackArch tool gets a launcher" 0 "Exec=cos-pause cos run 0d1n" cat "$MROOT/usr/share/applications/cos-tool-0d1n.desktop"
  printf '[Desktop Entry]\nName=Shodan CLI\nExec=sh -c "shodan host 1.1.1.1; bash"\nType=Application\n' > "$MROOT/usr/share/applications/shodan-launcher.desktop"
  check "cos menu: a tool whose command starts with 'sh' is still found" 0 "^[1-9]" sh -c "COS_ROOT='$MROOT' PYTHONPATH='$COS_LIB' python3 -c \"import cos_menu; print(1 if cos_menu.index_existing('$MROOT/usr/share/applications').get('shodan') else 0)\""
  check "palettes: dual, red and blue, valid JSON" 0 "^3$" python3 -c "import json;print(len(json.load(open('$COS_SHARE/palettes.json'))))"
else
  echo "skip  cos tests (python3 not available)"
fi
unset COS_SHARE COS_LIB

echo
echo "cli tests: $pass passed, $failed failed"
[ "$failed" -eq 0 ]
