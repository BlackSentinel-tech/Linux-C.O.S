def picom_conf(fx: str) -> str:
    high = fx == "high"
    body = PICOM_COMMON.format(fx=fx, backend="glx" if high else "xrender",
                               sr=22 if high else 14, sy=14 if high else 8,
                               so=0.55 if high else 0.45, cr=14 if high else 10)
    return body + (PICOM_HIGH if high else "") + PICOM_WINTYPES


