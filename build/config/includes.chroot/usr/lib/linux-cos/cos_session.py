"""Desktop session manager: turns (mode, fx level) into a running desktop.

`cos session start` runs at login; `cos mode` / `cos fx` call apply() again.
Everything generated lives in ~/.config/linux-cos/ so it is never overwritten
by an upgrade and a broken experiment is one `rm -r` away.

  fx high : picom (GLX: blur, rounded corners, shadows, animations), animated
            wallpaper, conky HUD           -- bare metal with a GPU
  fx low  : picom (xrender: shadows, fade, rounded corners), static wallpaper,
            conky HUD                      -- VMs, old hardware
  fx off  : xfwm4 compositing only, static wallpaper, no HUD
"""
from __future__ import annotations

import os
import shutil
import subprocess
import time

import cos_core as core

LIB = os.environ.get("COS_LIB", "/usr/lib/linux-cos")
BG = "/usr/share/backgrounds/linux-cos"
CFG = core.CONF_DIR


def _write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def _run(*argv: str, check: bool = False) -> int:
    try:
        return subprocess.run(argv, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=check).returncode
    except (OSError, subprocess.SubprocessError):
        return 127


def _spawn(*argv: str) -> None:
    """Start a detached background process; its output goes to ~/.cache/linux-cos/<name>.log."""
    logdir = os.path.expanduser("~/.cache/linux-cos")
    try:
        os.makedirs(logdir, exist_ok=True)
        log = open(os.path.join(logdir, os.path.basename(argv[0]).replace(".py", "") + ".log"), "w")
    except OSError:
        log = subprocess.DEVNULL
    try:
        subprocess.Popen(argv, stdin=subprocess.DEVNULL, stdout=log, stderr=log, start_new_session=True)
    except OSError:
        pass


def _kill(name: str) -> None:
    _run("pkill", "-u", str(os.getuid()), "-x", name)


def _xfset(channel: str, prop: str, typ: str, val: str) -> None:
    _run("xfconf-query", "-c", channel, "-p", prop, "-n", "-t", typ, "-s", val)


def _rgba(h: str, a: float) -> str:
    h = h.lstrip("#")
    return f"{int(h[0:2], 16) / 255:.3f}, {int(h[2:4], 16) / 255:.3f}, {int(h[4:6], 16) / 255:.3f}, {a}"


