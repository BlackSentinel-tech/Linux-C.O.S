"""Generate the unified Linux-C.O.S applications menu.

Kali ships its own .desktop entries under Kali's categories; Parrot and
BlackArch ship none.  This regroups EVERY tool under the same twenty
categories (see tools.tsv) and creates launcher entries for the tools that
have none, so the menu, the search box and `cos tools` all agree.

Run at image build time by the 0070 hook, and again by `cos menu`.
"""
from __future__ import annotations

import glob
import os
import re
import sys
from xml.sax.saxutils import escape

import cos_core as core

HEADER = '<!DOCTYPE Menu PUBLIC "-//freedesktop//DTD Menu 1.0//EN"\n "http://www.freedesktop.org/standards/menu-spec/1.0/menu.dtd">\n'


def _read_desktop(path: str) -> dict[str, str]:
    d: dict[str, str] = {}
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            in_entry = False
            for line in f:
                line = line.strip()
                if line.startswith("["):
                    in_entry = line == "[Desktop Entry]"
                elif in_entry and "=" in line and not line.startswith("#"):
                    k, v = line.split("=", 1)
                    d.setdefault(k, v)
    except OSError:
        pass
    return d


def index_existing(apps_dir: str) -> dict[str, str]:
    """tool name -> desktop file id of an entry that already launches it."""
    idx: dict[str, str] = {}
    for path in sorted(glob.glob(os.path.join(apps_dir, "*.desktop"))):
        fid = os.path.basename(path)
        if fid.startswith("cos-tool-") or fid.startswith("linux-cos-"):
            continue
        base = fid[:-8]
        keys = {base, re.sub(r"^(kali|parrot)-", "", base)}
        d = _read_desktop(path)
        if d.get("NoDisplay", "").lower() == "true" or d.get("Hidden", "").lower() == "true":
            continue
        wrappers = {"sh", "bash", "env", "sudo", "pkexec", "kali-treat-as-root", "x-terminal-emulator",
                    "xfce4-terminal", "cos-pause", "qterminal", "exo-open", "gtk-launch"}
        for tok in d.get("Exec", "").split():
            tok = os.path.basename(tok.strip("\"'"))
            if tok and tok not in wrappers and not tok.startswith(("-", "%")):
                keys.add(tok)
                break
        keys.add(d.get("Name", "").lower().replace(" ", "-"))
        for k in keys:
            if k:
                idx.setdefault(k, fid)
    return idx


def _tool_entry(t: core.Tool, cat: core.Category) -> str:
    src = core.SOURCE_LABEL.get(t.source, t.source)
    lines = [
        "[Desktop Entry]", "Type=Application", "Version=1.0",
        f"Name={t.name}",
        f"GenericName={src} · {cat.en}",
        f"GenericName[es]={src} · {cat.es}",
        f"Comment={src} tool -- opens a terminal and runs it (BlackArch tools run from the container)",
        f"Comment[es]=Herramienta de {src} -- abre una terminal y la ejecuta (las de BlackArch corren desde el contenedor)",
        f"Exec=cos-pause cos run {t.name}",
        "Terminal=true",
        f"Icon={cat.icon}",
        f"Categories=X-COS-{t.cat};",
        f"Keywords={t.name};{t.group};{src};{cat.en};",
        f"X-COS-Source={t.source}",
    ]
    return "\n".join(lines) + "\n"


def _directory(cat: core.Category) -> str:
    n = f"{cat.order:02d} {cat.en}"
    ne = f"{cat.order:02d} {cat.es}"
    return ("[Desktop Entry]\nType=Directory\n"
            f"Name={n}\nName[es]={ne}\nIcon={cat.icon}\n")


def generate(apps_dir: str, out_apps: str, menu_dir: str, dir_dir: str, quiet: bool = False) -> dict[str, int]:
    cats = core.categories()
    existing = index_existing(apps_dir)
    os.makedirs(out_apps, exist_ok=True)
    os.makedirs(menu_dir, exist_ok=True)
    os.makedirs(dir_dir, exist_ok=True)

    by_cat: dict[str, list[str]] = {c: [] for c in cats}
    made = reused = 0
    for t in core.tools().values():
        if t.source == "cos" or t.cat not in cats:
            continue
        fid = existing.get(t.name)
        if fid:
            reused += 1
        else:
            fid = f"cos-tool-{t.name}.desktop"
            with open(os.path.join(out_apps, fid), "w", encoding="utf-8") as f:
                f.write(_tool_entry(t, cats[t.cat]))
            made += 1
        by_cat[t.cat].append(fid)

    xml = [HEADER, "<!-- GENERATED by cos_menu.py (rebuild with: cos menu) -->\n<Menu>\n  <Name>Applications</Name>\n"]
    for c in sorted(cats.values(), key=lambda c: c.order):
        files = sorted(set(by_cat[c.id]), key=str.lower)
        if not files:
            continue
        with open(os.path.join(dir_dir, f"cos-{c.id}.directory"), "w", encoding="utf-8") as f:
            f.write(_directory(c))
        xml.append(f"  <Menu>\n    <Name>cos-{c.id}</Name>\n    <Directory>cos-{c.id}.directory</Directory>\n    <Include>\n")
        xml.extend(f"      <Filename>{escape(fid)}</Filename>\n" for fid in files)
        xml.append("    </Include>\n  </Menu>\n")
    xml.append("</Menu>\n")
    with open(os.path.join(menu_dir, "linux-cos-tools.menu"), "w", encoding="utf-8") as f:
        f.write("".join(xml))
    if not quiet:
        print(f"menu: {reused} existing entries regrouped, {made} created, {len(cats)} categories")
    return {"reused": reused, "created": made}


def prune_docklike(rc_path: str, apps_dir: str) -> int:
    """Keep only pinned launchers whose .desktop file exists (a missing one shows as a blank icon)."""
    try:
        with open(rc_path, encoding="utf-8") as f:
            lines = f.read().splitlines()
    except OSError:
        return 0
    out, dropped = [], 0
    for line in lines:
        if line.startswith("pinned="):
            keep = []
            for fid in [x for x in line[7:].split(";") if x]:
                if os.path.exists(os.path.join(apps_dir, fid if fid.endswith(".desktop") else fid + ".desktop")):
                    keep.append(fid)
                else:
                    dropped += 1
            line = "pinned=" + ";".join(keep) + (";" if keep else "")
        out.append(line)
    with open(rc_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    return dropped


def main(argv: list[str]) -> int:
    root = os.environ.get("COS_ROOT", "")
    generate(root + "/usr/share/applications", root + "/usr/share/applications",
             root + "/etc/xdg/menus/applications-merged", root + "/usr/share/desktop-directories")
    n = prune_docklike(root + "/etc/skel/.config/xfce4/panel/docklike.rc", root + "/usr/share/applications")
    if n:
        print(f"dock: dropped {n} pinned launchers that are not installed")
    # Kali's own menu tree would list every tool a second time under Kali's categories
    kali_menu = root + "/etc/xdg/menus/applications-merged/kali-applications.menu"
    if os.path.exists(kali_menu):
        os.remove(kali_menu)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
